#!/usr/bin/env node
// Bundles the registry, prompt files, catalog, scenes, missions, and samples into studio/assets/data.js.
// The studio loads it with a classic <script> tag, so it also works from file://.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import YAML from 'yaml';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_FILE = join(ROOT, 'studio', 'assets', 'data.js');

const readJson = (rel) => JSON.parse(readFileSync(join(ROOT, rel), 'utf8'));

export function parsePromptFile(text) {
  const normalized = text.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error('Prompt file has no YAML frontmatter.');
  return { frontmatter: YAML.parse(match[1]) || {}, body: match[2].trim() };
}

export function loadPrompts() {
  const dir = join(ROOT, '.github', 'prompts');
  const prompts = {};
  for (const file of readdirSync(dir).filter((name) => name.endsWith('.prompt.md')).sort()) {
    const { frontmatter, body } = parsePromptFile(readFileSync(join(dir, file), 'utf8'));
    const name = file.replace(/\.prompt\.md$/, '');
    prompts[name] = {
      file: `.github/prompts/${file}`,
      name: frontmatter.name,
      description: frontmatter.description,
      argumentHint: frontmatter['argument-hint'] || '',
      agent: frontmatter.agent,
      tools: Array.isArray(frontmatter.tools) ? frontmatter.tools : [],
      body,
    };
  }
  return prompts;
}

export function buildStudioData() {
  const data = {
    registry: readJson('commands.json'),
    prompts: loadPrompts(),
    catalog: readJson('exercises/catalog.json'),
    scenes: readJson('demo/scenarios.json').scenes,
    missions: readJson('studio/missions.json'),
    samples: readJson('demo/samples.json'),
  };
  delete data.samples.$comment;
  return data;
}

export function renderDataFile(data = buildStudioData()) {
  return '// Generated by scripts/build-studio-data.mjs. Do not edit by hand; run npm run build:studio.\n'
    + `globalThis.STUDIO_DATA = ${JSON.stringify(data, null, 2)};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = renderDataFile();
  writeFileSync(DATA_FILE, text);
  console.log(`Wrote studio/assets/data.js (${Buffer.byteLength(text)} bytes).`);
}
