import { join } from 'node:path';
import { ROOT, SITE, esc, inline, urlFrom } from './util.mjs';
import { docOutput } from './data.mjs';

export const PAGES = {
  home: join(SITE, 'index.html'),
  commands: join(SITE, 'commands.html'),
  skills: join(SITE, 'skills.html'),
  studio: join(ROOT, 'commands', 'studio', 'index.html'),
  css: join(SITE, 'assets', 'site.css'),
  js: join(SITE, 'assets', 'site.js'),
};

export const REPOSITORY = 'https://github.com/AkashAi7/anti-ai-slop';
export const DOWNLOAD = `${REPOSITORY}/archive/refs/heads/main.zip`;

const NAV = [
  ['home', 'Home'],
  ['commands', 'Commands lab'],
  ['skills', 'Skills lab'],
  ['studio', 'Command Studio'],
];

// `title` must already be HTML-safe.
export function page({ file, title, description, active, body }) {
  const to = (target) => urlFrom(file, target);
  const links = NAV.map(([id, label]) => {
    const current = id === active ? ' aria-current="page"' : '';
    return `<li><a href="${to(PAGES[id])}"${current}>${label}</a></li>`;
  }).join('');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title === 'Anti-Slop Labs' ? title : `${title} - Anti-Slop Labs`}</title>
<meta name="description" content="${esc(description)}">
<meta name="generator" content="site/scripts/build.mjs">
<link rel="stylesheet" href="${to(PAGES.css)}">
<script src="${to(PAGES.js)}" defer></script>
</head>
<body>
<!-- Generated by site/scripts/build.mjs from the lab sources. Edit the sources, then run npm run build in site/. -->
<a class="skip-link" href="#main">Skip to content</a>
<header class="site-header">
<div class="wrap header-inner">
<a class="brand" href="${to(PAGES.home)}"><span class="brand-mark" aria-hidden="true">/</span><span class="brand-name">Anti-Slop Labs</span></a>
<nav aria-label="Primary"><ul class="nav">${links}</ul></nav>
</div>
</header>
<main id="main" tabindex="-1">
${body}
</main>
<footer class="site-footer">
<div class="wrap footer-inner">
<p>Walkthroughs and studio scenes are <strong>illustrative</strong>, not recorded Copilot output. Only the Commands lab GIFs show real check results, re-run by the recorder before each capture. No productivity statistics are claimed.</p>
<p>Records of what was actually run: <a href="${to(join(SITE, 'docs', 'commands', 'VERIFICATION.html'))}">Commands lab</a> · <a href="${to(join(SITE, 'docs', 'skills', 'VERIFICATION.html'))}">Skills lab</a> · <a href="${to(join(SITE, 'docs', 'site', 'README.html'))}">About this site</a></p>
<p><a href="${to(PAGES.home)}#get-lab">Prerequisites and setup</a> · <a href="${REPOSITORY}">GitHub repository</a> · <a href="${DOWNLOAD}">Download exercises (ZIP)</a></p>
</div>
</footer>
</body>
</html>
`;
}

export function player(file, walk, label = walk.title) {
  const to = (target) => urlFrom(file, target);
  const alt = `Illustrative walkthrough: ${walk.title}.${walk.takeaway ? ` ${walk.takeaway}` : ''}`;
  const transcript = to(docOutput(walk.transcript));
  return `<figure class="player">
<div class="player-media">
<img src="${to(walk.poster)}" data-poster="${to(walk.poster)}" data-gif="${to(walk.gif)}" alt="${esc(alt)}" width="1280" height="720" loading="lazy" decoding="async">
</div>
<figcaption class="player-bar"><button type="button" class="player-toggle" hidden aria-haspopup="dialog" data-label="${esc(label)}" data-transcript="${transcript}">Play full screen<span class="sr-only">: ${esc(label)}</span></button><span class="player-links"><span class="tag">Illustrative</span> <a href="${to(walk.gif)}">GIF</a>${walk.id === 'studio-tour' ? '' : ` · <a href="${to(walk.before)}">Before</a> · <a href="${to(walk.after)}">After</a>`} · <a href="${transcript}">Transcript</a></span></figcaption>
</figure>`;
}

export const flow = (steps, prefix = '/') =>
  `<ol class="flow" aria-label="Flow">${steps.map((step) => `<li><code>${esc(prefix + step)}</code></li>`).join('')}</ol>`;

export function guideList(file, guides) {
  const items = guides.map(([target, label, about]) =>
    `<li><a href="${urlFrom(file, target)}">${label}</a><span>${inline(about)}</span></li>`).join('\n');
  return `<ul class="guides">\n${items}\n</ul>`;
}

export const command = (text) => `<pre class="cmd"><code>${esc(text)}</code></pre>`;

export function getLab(lab) {
  return `<p>Get the starter code, checks, hints, and reference solutions from the <a href="${REPOSITORY}">GitHub repository</a>, or <a href="${DOWNLOAD}">download and extract the ZIP</a>. GitHub Pages hosts the demos; real exercises run locally.</p>
${command(`git clone ${REPOSITORY}.git\ncd anti-ai-slop/${lab}`)}
<p class="note">Already cloned? Open the <code>${lab}</code> folder in your existing copy. ZIP downloads extract to <code>anti-ai-slop-main</code>; open its <code>${lab}</code> folder instead.</p>`;
}
