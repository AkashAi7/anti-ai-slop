import { join } from 'node:path';
import { DOWNLOADS, REPOSITORY, SITE, esc, urlFrom } from './util.mjs';
import { DOCS, transcriptOutput } from './data.mjs';

export const PAGES = {
  home: join(SITE, 'index.html'),
  setup: DOCS.setup.output,
  'lab-1': DOCS['lab-1'].output,
  'lab-2': DOCS['lab-2'].output,
  facilitator: DOCS.facilitator.output,
  verification: DOCS.verification.output,
  notices: DOCS.notices.output,
  css: join(SITE, 'assets', 'site.css'),
  js: join(SITE, 'assets', 'site.js'),
};

const NAV = [
  ['home', 'Home'],
  ['setup', 'Setup'],
  ['lab-1', 'Lab 1: /commands + Spec Kit'],
  ['lab-2', 'Lab 2: anti-slop skills'],
  ['facilitator', 'Facilitator'],
];

// `title` must already be HTML-safe.
export function page({ file, title, description, active, body }) {
  const to = (target) => urlFrom(file, target);
  const links = NAV.map(([id, label]) => {
    const current = id === active ? ' aria-current="page"' : '';
    return `<li><a href="${to(PAGES[id])}"${current}>${label}</a></li>`;
  }).join('');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title === 'Anti-Slop Labs' ? title : `${title} - Anti-Slop Labs`}</title>
<meta name="description" content="${esc(description)}">
<meta name="generator" content="site/scripts/build.mjs">
<link rel="stylesheet" href="${to(PAGES.css)}">
<script src="${to(PAGES.js)}" defer></script>
</head>
<body>
<!-- Generated by site/scripts/build.mjs from lab/. Edit the lab sources, then run npm run build in site/. -->
<a class="skip-link" href="#main">Skip to content</a>
<header class="site-header">
<div class="wrap header-inner">
<a class="brand" href="${to(PAGES.home)}"><span class="brand-mark" aria-hidden="true">/</span><span class="brand-name">Anti-Slop Labs</span></a>
<nav aria-label="Primary"><ul class="nav">${links}</ul></nav>
</div>
</header>
<main id="main" tabindex="-1">
${body}
</main>
<footer class="site-footer">
<div class="wrap footer-inner">
<p>Walkthrough GIFs are <strong>illustrative reenactments</strong>: the chat dialogue is authored, not recorded Copilot output. Their test results come from real fixture runs. No productivity statistics are claimed.</p>
<p><a href="${to(PAGES.verification)}">Verification and limitations</a> · <a href="${to(PAGES.notices)}">Third-party notices</a> · <a href="${REPOSITORY}">GitHub repository</a> · <a href="${to(DOWNLOADS.lab)}" download>Download the lab (ZIP)</a></p>
</div>
</footer>
</body>
</html>
`;
}

export function player(file, walk, { label = walk.title, eager = false } = {}) {
  const to = (target) => urlFrom(file, target);
  const alt = `Illustrative walkthrough: ${walk.title} ${walk.takeaway}`;
  const transcript = to(transcriptOutput(walk.id));
  return `<figure class="player">
<div class="player-media">
<img src="${to(walk.poster)}" data-poster="${to(walk.poster)}" data-gif="${to(walk.gif)}" alt="${esc(alt)}" width="1280" height="720"${eager ? '' : ' loading="lazy"'} decoding="async">
</div>
<figcaption class="player-bar"><button type="button" class="player-toggle" hidden aria-haspopup="dialog" data-label="${esc(label)}" data-transcript="${transcript}">Play full screen<span class="sr-only">: ${esc(label)}</span></button><span class="player-links"><span class="tag">Illustrative</span> <a href="${to(walk.gif)}">GIF</a> · <a href="${to(walk.before)}">Before</a> · <a href="${to(walk.after)}">After</a> · <a href="${transcript}">Transcript</a></span></figcaption>
</figure>`;
}

export const flow = (steps) =>
  `<ol class="flow" aria-label="Commands in order">${steps.map((step) => `<li><code>/${esc(step)}</code></li>`).join('')}</ol>`;

export const command = (text) => `<pre class="cmd"><code>${esc(text)}</code></pre>`;

// Labels must already be HTML-safe (rendered heading text).
export function toc(entries) {
  if (!entries.length) return '';
  const items = entries.map(({ id, label }) => `<li><a href="#${id}">${label}</a></li>`).join('');
  return `<nav class="toc" aria-label="On this page"><p class="toc-title">On this page</p><ol>${items}</ol></nav>`;
}
